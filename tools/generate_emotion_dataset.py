def char_to_yaml(ch):
    """Convert a character to Unity YAML format."""
    code = ord(ch)
    if code > 127:
        return f"\\u{code:04X}"
    return ch


def pattern_to_yaml(pattern):
    """Convert a regex pattern string to Unity YAML escaped format."""
    result = []
    i = 0
    while i < len(pattern):
        ch = pattern[i]
        if ch == '\\' and i + 1 < len(pattern):
            next_ch = pattern[i + 1]
            if next_ch == 'u' and i + 5 < len(pattern):
                # Might be a unicode escape already - skip
                pass
            # Regex escape: \s, \b, \d, \w, \S, \B, \D, \W, etc.
            result.append('\\\\')
            result.append(next_ch)
            i += 2
            continue
        elif ord(ch) > 127:
            result.append(f"\\u{ord(ch):04X}")
        else:
            result.append(ch)
        i += 1
    return ''.join(result)


def tag_to_yaml(tag):
    """Convert an emotion tag string to Unity YAML escaped format."""
    return ''.join(f"\\u{ord(ch):04X}" if ord(ch) > 127 else ch for ch in tag)


def generate_asset(patterns, output_path):
    """Generate the Unity .asset YAML file."""
    header = """%YAML 1.1
%TAG !u! tag:unity3d.com,2011:
--- !u!114 &11400000
MonoBehaviour:
  m_ObjectHideFlags: 0
  m_CorrespondingSourceObject: {fileID: 0}
  m_PrefabInstance: {fileID: 0}
  m_PrefabAsset: {fileID: 0}
  m_GameObject: {fileID: 0}
  m_Enabled: 1
  m_EditorHideFlags: 0
  m_Script: {fileID: 11500000, guid: b036aa10c55c8eb40a9834f43913e8b3, type: 3}
  m_Name: EmotionKeywordDataset
  m_EditorClassIdentifier: FluentT.AvatarControllerSampleFloatingHead.Runtime::FluentT.Avatar.SampleFloatingHead.EmotionKeywordDataset
  entries:
"""

    with open(output_path, 'w', encoding='utf-8') as f:
        f.write(header)
        for pattern, tag, weight in patterns:
            yaml_pattern = pattern_to_yaml(pattern)
            yaml_tag = tag_to_yaml(tag)
            # Format weight: use integer if whole number
            if weight == int(weight):
                weight_str = str(int(weight))
            else:
                weight_str = str(weight)
            f.write(f'  - pattern: "{yaml_pattern}"\n')
            f.write(f'    emotionTag: "{yaml_tag}"\n')
            f.write(f'    weight: {weight_str}\n')

    print(f"생성 완료: {output_path}")
    print(f"총 {len(patterns)}개 항목")

